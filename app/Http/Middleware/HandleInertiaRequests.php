<?php

namespace App\Http\Middleware;

use App\Support\SystemAccess;
use Illuminate\Http\Request;
use Inertia\Middleware;
use Spatie\Permission\Models\Permission;

class HandleInertiaRequests extends Middleware
{
    /**
     * The root template that's loaded on the first page visit.
     *
     * @see https://inertiajs.com/server-side-setup#root-template
     *
     * @var string
     */
    protected $rootView = 'app';

    /**
     * Determines the current asset version.
     *
     * @see https://inertiajs.com/asset-versioning
     */
    public function version(Request $request): ?string
    {
        return parent::version($request);
    }

    /**
     * Define the props that are shared by default.
     *
     * @see https://inertiajs.com/shared-data
     *
     * @return array<string, mixed>
     */
    public function share(Request $request): array
    {
        $user = $request->user();

        return [
            ...parent::share($request),
            'auth' => [
                'user' => $user ? [
                    'id' => $user->id,
                    'name' => $user->name,
                    'email' => $user->email,
                    'avatar' => $user->avatar,
                    'role' => $user->roles->first()?->name,
                ] : null,
                // Permission names gate menus and buttons in Vue; the server
                // remains the authority that actually enforces them. The
                // SuperAdmin role bypasses checks via Gate::before without
                // holding synced permissions, so mirror that rule here by
                // sharing every permission name for its holders.
                'permissions' => $user
                    ? ($user->hasRole(SystemAccess::SUPER_ADMIN_ROLE)
                        ? Permission::pluck('name')->all()
                        : $user->getAllPermissions()->pluck('name')->all())
                    : [],
            ],
            'flash' => [
                'success' => fn () => $request->session()->get('success'),
                'error' => fn () => $request->session()->get('error'),
            ],
        ];
    }
}
